'use strict';

const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  listProducts: () => ipcRenderer.invoke('products:list'),
  saveProduct: (product) => ipcRenderer.invoke('products:save', product),
  deleteProduct: (id) => ipcRenderer.invoke('products:delete', id),
  pickImages: () => ipcRenderer.invoke('images:pick'),
  removeImage: (name) => ipcRenderer.invoke('images:remove', name),
  pickVideo: () => ipcRenderer.invoke('videos:pick'),
  removeVideo: (name) => ipcRenderer.invoke('videos:remove', name),
  listCategories: () => ipcRenderer.invoke('categories:list'),
  addCategory: (name) => ipcRenderer.invoke('categories:add', name),
  removeCategory: (name) => ipcRenderer.invoke('categories:remove', name),
  listOrders: () => ipcRenderer.invoke('orders:list'),
  cancelOrder: (id, reason) => ipcRenderer.invoke('orders:cancel', id, reason),
  setOrderTracking: (id, code) => ipcRenderer.invoke('orders:tracking', id, code),
  listViews: () => ipcRenderer.invoke('views:list'),
  listAbuse: () => ipcRenderer.invoke('abuse:list'),
  blockUser: (chatId, reason) => ipcRenderer.invoke('abuse:block', chatId, reason),
  unblockUser: (chatId) => ipcRenderer.invoke('abuse:unblock', chatId),
  onAbuseChanged: (cb) => ipcRenderer.on('abuse:changed', () => cb()),
  listOptions: (kind) => ipcRenderer.invoke('options:list', kind),
  addOption: (kind, value) => ipcRenderer.invoke('options:add', kind, value),
  removeOption: (kind, value) => ipcRenderer.invoke('options:remove', kind, value),
  renameOption: (kind, from, to) => ipcRenderer.invoke('options:rename', kind, from, to),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  saveSettings: (settings) => ipcRenderer.invoke('settings:save', settings),
  botStart: (messenger) => ipcRenderer.invoke('bot:start', messenger),
  botStop: (messenger) => ipcRenderer.invoke('bot:stop', messenger),
  getBotStatuses: () => ipcRenderer.invoke('bot:statuses'),
  onBotStatus: (cb) => ipcRenderer.on('bot:status', (_event, status) => cb(status)),
  getAppInfo: () => ipcRenderer.invoke('app:info'),
  openDataDir: () => ipcRenderer.invoke('app:openDataDir'),
  onProductsChanged: (cb) => ipcRenderer.on('products:changed', () => cb()),
});
